"""Derive the `philadelphia` anchor set in config/demand_baseline.yaml from real segments.

The reference set is the priced curb of data/processed/segments.parquet (scripts/02;
`priced_curb`, see config/zones.yaml): the blocks the scenarios price. Each center is the
mean and each scale the standard deviation of log1p(covariate) over that set, and
intensity_low / intensity_high its 5th and 95th percentiles of lambda under those centers and
scales. Values are rounded to 2 decimals and written between the BEGIN / END philadelphia
markers. `--check` exits 1 if the config differs from what the segments give.
"""
from __future__ import annotations

import sys

import click
import numpy as np
import pandas as pd

from phillyparking._config import data_dir, project_root

BEGIN = "  # BEGIN philadelphia (generated by scripts/derive_baseline_anchors.py; do not edit by hand)"
END = "  # END philadelphia"


def derive(segments: pd.DataFrame, weights: dict) -> dict:
    ref = segments[segments["priced_curb"].astype(bool)]
    if len(ref) < 30:
        raise SystemExit(f"only {len(ref)} priced-curb segments; build segments first (script 02)")
    logs = {c: np.log1p(ref[c].to_numpy(dtype=float)) for c in weights}
    centers = {c: round(float(v.mean()), 2) for c, v in logs.items()}
    scales = {c: round(float(v.std(ddof=0)), 2) for c, v in logs.items()}
    lam = sum(float(weights[c]["intensity_weight"]) * (logs[c] - centers[c]) / scales[c]
              for c in weights)
    return {"n": len(ref), "centers": centers, "scales": scales,
            "intensity_low": round(float(np.percentile(lam, 5)), 2),
            "intensity_high": round(float(np.percentile(lam, 95)), 2)}


def block(d: dict, rule: str | None) -> str:
    import json

    fmt = lambda m: "{ " + ", ".join(f"{k}: {v:.2f}" for k, v in m.items()) + " }"  # noqa: E731
    return "\n".join([
        BEGIN,
        "  philadelphia:",
        "    reference: " + json.dumps(f"priced curb of data/processed/segments.parquet, "
                                     f"n={d['n']}" + (f"; {rule}" if rule else "")),
        f"    centers: {fmt(d['centers'])}",
        f"    scales:  {fmt(d['scales'])}",
        f"    intensity_low: {d['intensity_low']:.2f}",
        f"    intensity_high: {d['intensity_high']:.2f}",
        END,
    ])


@click.command()
@click.option("--check", is_flag=True, help="Exit 1 if the config is stale; write nothing.")
def main(check: bool) -> None:
    import json

    import yaml

    cfg_path = project_root() / "config" / "demand_baseline.yaml"
    text = cfg_path.read_text(encoding="utf-8")
    proc = data_dir() / "processed"
    segs = pd.read_parquet(proc / "segments.parquet")
    meta_path = proc / "segments.meta.json"
    rule = (json.loads(meta_path.read_text(encoding="utf-8")).get("priced_curb_rule")
            if meta_path.exists() else None)
    start, end = text.index(BEGIN), text.index(END) + len(END)
    weights = yaml.safe_load(text[:start] + text[end:])["covariates"]
    new = block(derive(segs, weights), rule)
    current = text[start:end]
    if check:
        if current != new:
            print("config/demand_baseline.yaml philadelphia anchors are stale:\n"
                  f"--- config\n{current}\n+++ derived\n{new}")
            sys.exit(1)
        print("philadelphia anchors up to date")
        return
    cfg_path.write_text(text[:start] + new + text[end:], encoding="utf-8")
    print(new)


if __name__ == "__main__":
    main()
